#!/usr/bin/env bash
# Rejoue les brouillons sur une base Postgres VIDE et jetable, puis lance
# les tests. Jamais sur la prod ni la preprod : stub.sql y créerait de
# fausses tables.
#
#   ./run.sh "postgresql://postgres@localhost:5432/tiroir_drafts_test"
set -euo pipefail
DB="${1:?Usage : ./run.sh URL_DE_BASE_POSTGRES_VIDE}"
HERE="$(cd "$(dirname "$0")" && pwd)"
psql "$DB" -q -f "$HERE/stub.sql" >/dev/null 2>&1 || true
psql "$DB" -q -v ON_ERROR_STOP=1 -f "$HERE/../../migrations/20260930080000_ai_credits.sql"
psql "$DB" -q -f "$HERE/ai_credits.test.sql" | tee /dev/stderr | tail -3 | grep -qE "^ +0$"
echo "✓ ai_credits : tous les tests passent"
psql "$DB" -q -v ON_ERROR_STOP=1 -f "$HERE/stub_spend.sql"
psql "$DB" -q -v ON_ERROR_STOP=1 -f "$HERE/../../migrations/20261108143238_ai_credits_spend.sql"
psql "$DB" -q -f "$HERE/ai_credits_spend.test.sql" | tee /dev/stderr | tail -3 | grep -qE "^ +0$"
echo "✓ ai_credits_spend : tous les tests passent"
psql "$DB" -q -v ON_ERROR_STOP=1 -f "$HERE/../../migrations/20261109055040_refund_ai_credits_lock.sql"
psql "$DB" -q -v lockfile="$HERE/../../migrations/20261109055040_refund_ai_credits_lock.sql" -f "$HERE/refund_ai_credits_lock.test.sql" | tee /dev/stderr | tail -3 | grep -qE "^ +0$"
echo "✓ refund_ai_credits_lock : tous les tests passent"
psql "$DB" -q -v ON_ERROR_STOP=1 -f "$HERE/../../migrations/20261108143328_stripe_credits.sql"
psql "$DB" -q -f "$HERE/stripe_credits.test.sql" | tee /dev/stderr | tail -3 | grep -qE "^ +0$"
echo "✓ stripe_credits : tous les tests passent"
psql "$DB" -q -v ON_ERROR_STOP=1 -f "$HERE/stub_business.sql"
psql "$DB" -q -v ON_ERROR_STOP=1 -f "$HERE/../business_billing.sql"
psql "$DB" -q -f "$HERE/business_billing.test.sql" | tee /dev/stderr | tail -3 | grep -qE "^ +0$"
echo "✓ business_billing : tous les tests passent"
psql "$DB" -q -v ON_ERROR_STOP=1 -f "$HERE/../../migrations/20261108130727_stripe_subscriptions.sql"
psql "$DB" -q -f "$HERE/stripe_subscriptions.test.sql" | tee /dev/stderr | tail -3 | grep -qE "^ +0$"
echo "✓ stripe_subscriptions : tous les tests passent"
psql "$DB" -q -v ON_ERROR_STOP=1 -f "$HERE/../../migrations/20261109050731_stripe_end_keeps_store.sql"
psql "$DB" -q -f "$HERE/stripe_end_keeps_store.test.sql" | tee /dev/stderr | tail -3 | grep -qE "^ +0$"
echo "✓ stripe_end_keeps_store : tous les tests passent"
psql "$DB" -q -v ON_ERROR_STOP=1 -f "$HERE/../../migrations/20261108143334_checkout_consents.sql"
psql "$DB" -q -f "$HERE/checkout_consents.test.sql" | tee /dev/stderr | tail -3 | grep -qE "^ +0$"
echo "✓ checkout_consents : tous les tests passent"
psql "$DB" -q -v ON_ERROR_STOP=1 -f "$HERE/../../migrations/20260625173437_create_share_links.sql"
psql "$DB" -q -v ON_ERROR_STOP=1 -f "$HERE/../../migrations/20261111160815_share_links_private.sql"
psql "$DB" -q -v privatefile="$HERE/../../migrations/20261111160815_share_links_private.sql" -f "$HERE/share_links_private.test.sql" | tee /dev/stderr | tail -3 | grep -qE "^ +0$"
echo "✓ share_links_private : tous les tests passent"
